// Поиск арены по кадру — для мобильного клиента.
//
// В мобильном клиенте камера ходит: арена то приближается, то отдаляется,
// и даже смещается. Поэтому область поля нельзя задать константой — её
// приходится искать в каждом кадре.
//
// Плитки арены — яркие жёлто-зелёные (H≈28..40, S>170, V>170). Верхняя
// половина (чужая) и нижняя (своя) делятся кадр пополам; в каждую группу
// попадают все куски плиток, и по ним берётся общий прямоугольник — так
// арена находится даже когда её часть закрыта эффектом волны.
#pragma once

#include <opencv2/core.hpp>

namespace rr {

// Найденные половины арены в координатах холста.
struct ArenaFrame {
    bool found = false;
    // Верхняя половина — поле противника.
    cv::Rect top;
    // Нижняя половина — своё поле.
    cv::Rect bottom;
    // Обе половины вместе (между ними полоса со счётчиком волны).
    cv::Rect full;
    // Сколько плиток нашлось в каждой половине: мало — значит, арена
    // перекрыта и найденное место сомнительно.
    int tiles_top = 0;
    int tiles_bottom = 0;
    // Сторона определяется положением точки внутри прямоугольника, а не
    // только высотой. Так нужно в «Подземельях» (Co-Op): там своё поле —
    // комната внизу, а по дороге к ней ходят и свои, и чужие юниты, и по
    // одной высоте их не различить.
    bool bounded = false;
};

// Найти арену на кадре холста мобильного клиента.
ArenaFrame find_arena(const cv::Mat& canvas);

// Арена в «Подземельях» (режим Co-Op): вместо цветных плиток — комнаты,
// обнесённые кремовыми стенами. Сверху чужая комната, снизу наша.
ArenaFrame find_arena_dungeon(const cv::Mat& canvas);

// Найти арену в геометрии канонического кадра.
//
// Прямоугольники половин собираются «посевом и расширением» — так же,
// как в tools/prepare_real_frames.py. От этого зависит канонический кадр,
// а значит и совпадение с эталонами юнитов: с правилом find_arena половины
// выходят другого размера и эталоны не совпадают.
ArenaFrame find_arena_canonical(const cv::Mat& canvas);

// Круглое основание юнита: по нему юнит стоит на поле.
struct PawnBase {
    cv::Point center;
    int radius = 0;
};

// Найти основания юнитов (круги) внутри половин арены.
//
// Основание — круг под юнитом; по нему же определяется масштаб кадра:
// камера в бою ходит, и без приведения к общему масштабу эталон юнита
// перестал бы совпадать.
std::vector<PawnBase> find_unit_bases(const cv::Mat& canvas,
                                       const std::vector<cv::Rect>& halves);

// Обратное преобразование: точка канонического поля -> точка кадра.
//
// Нужно, чтобы по найденному юниту понять, куда в кадре тянуть карточку
// (например, чтобы поставить её прямо на такого же юнита — слияние).
struct BoardMapping {
    // Прямоугольники половин арены в кадре (верхняя, нижняя).
    cv::Rect half[2];
    // Масштаб, применённый к половинам при сборке канонического кадра.
    double factor = 1.0;
    // Сдвиг половины на канонической доске.
    int left[2] = {0, 0};
    int top[2] = {0, 0};

    // Перевести точку доски в точку кадра.
    // (-1, -1), если точка не попадает ни в одну половину.
    cv::Point to_frame(cv::Point board_point) const;
};

// Собрать канонический кадр мобильного клиента.
//
// Так же, как `tools/prepare_real_frames.py`: верхняя половина арены,
// полоса со счётчиком волны, нижняя половина. Каждая половина приводится к
// общему масштабу — по медианному радиусу оснований юнитов, — поэтому
// размер юнита в кадре не зависит от того, как близко стоит камера.
//
// Размер кадра — 400x522. Если задан mapping, в него кладётся обратное
// преобразование «доска -> кадр».
cv::Mat canonical_board(const cv::Mat& canvas, BoardMapping* mapping = nullptr);

// Размеры канонического кадра мобильного клиента.
inline const int kCanonicalW = 400;
inline const int kCanonicalH = 522;
// Высота половины арены в каноническом кадре и высота полосы волны.
inline const int kCanonicalHalfH = 240;
inline const int kCanonicalGap = 42;
// Радиус основания юнита в каноническом кадре: к нему приводятся все
// эталоны юнитов.
inline const double kCanonicalRefRadius = 31.0;

}  // namespace rr
