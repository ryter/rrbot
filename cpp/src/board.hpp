// Сетка высадки и занятость доски.
//
// Поле боя — сетка клеток. На своей стороне их 5x3 (замерено в живых боях:
// 15 клеток; когда все заняты, виджет призыва гаснет и юнит не появляется —
// см. notes/ЗАДАЧА4_ДОСКА.md).
//
// Бот должен знать, сколько клеток ещё свободно: по этому решается, звать ли
// юнита (когда места нет, призыв всё равно не создаст юнита) и пора ли
// сливать (слияние бесплатное и освобождает клетку).
//
// Сетка не задаётся константой: камера в бою ходит, поле то приближается, то
// отдаляется. Поэтому шаг и начало сетки оцениваются по самим пешкам:
// шаг — около 2.5 радиуса основания, начало — по остаткам координат.
#pragma once

#include <opencv2/core.hpp>

#include <utility>
#include <vector>

#include "arena.hpp"
#include "merge.hpp"

namespace rr {

// Сколько клеток высадки на своей стороне (5 столбцов x 3 ряда).
inline const int kDeployCols = 5;
inline const int kDeployRows = 3;
inline const int kDeployCapacity = kDeployCols * kDeployRows;

// Порог «пестроты» клетки: выше — клетка занята.
//
// Пустая клетка — ровная плитка, и разброс яркости в пятне клетки мал
// (5..11 в замерах). На занятой клетке лежит основание с юнитом, и разброс
// большой (43..64). Порог лежит посередине.
inline const double kCellBusyThreshold = 25.0;

// Сетка клеток поля.
struct CellGrid {
    // Оценена ли сетка (по пешкам).
    bool valid = false;
    // Шаг сетки в пикселях кадра.
    double spacing = 0.0;
    // Начало сетки: координаты клетки (0, 0) по модулю шага.
    double phase_x = 0.0;
    double phase_y = 0.0;
    // Сколько пешек подтвердили сетку (из скольких рассматривали).
    int inliers = 0;
    int considered = 0;

    // Клетка, в которую попадает точка. Индексы относительные (нумерация
    // клеток не важна — важно, что две пешки в одной клетке дают один и тот
    // же индекс).
    std::pair<int, int> cell_of(cv::Point point) const;
    // Обратное: центр клетки в координатах кадра.
    //
    // Индексы клеток не зависят от положения камеры (в отличие от
    // координат относительно арены: детектор арены гуляет на десятки
    // пикселей), поэтому по ним удобно помнить «клетку слитого юнита» или
    // «клетку, с которой слияние не вышло».
    cv::Point point_of(std::pair<int, int> cell) const;
};

// Состояние доски: сколько клеток высадки занято.
struct BoardState {
    // Удалось ли оценить доску.
    bool valid = false;
    // Всего клеток высадки (kDeployCapacity).
    int capacity = kDeployCapacity;
    // Занято клеток.
    int occupied = 0;
    // Сколько осталось свободных.
    int free_cells = kDeployCapacity;
    // Занятые клетки (относительные индексы).
    std::vector<std::pair<int, int>> occupied_cells;
    // Сетка, по которой считали.
    CellGrid grid;
    // «Пестрота» каждой клетки (разброс яркости в пятне клетки).
    std::vector<double> cell_busy;
};

// Оценить сетку клеток по пешкам.
//
// Шаг сетки ищется перебором вокруг 2.5 радиуса основания: для каждого
// шага считается, сколько пешек попадает в одну решётку (остатки координат
// по модулю шага должны совпадать). Выбирается тот шаг, который подтверждает
// больше всего пешек.
//
// Пешки, стоящие не на клетке (юнит идёт по полю), решётку не подтверждают и
// в подсчёт занятых клеток не попадают.
CellGrid estimate_grid(const std::vector<Pawn>& pawns);

// Занятость своей половины поля.
//
// Клетка считается занятой, если на ней что-то есть: основание с юнитом или
// камнем. Пустая клетка — ровная плитка (разброс яркости в пятне клетки
// мал), занятая — пёстрая (основание, юнит). Так считаются все юниты,
// включая слитые: у них форма основания другая, и круглые основания их не
// находят.
BoardState analyze_board(const cv::Mat& canvas,
                         const ArenaFrame& arena,
                         const std::vector<Pawn>& pawns);

}  // namespace rr
