Layout emulator_layout() {
    // Кадр устройства 941x1030 (окно эмулятора), области сняты с боя.
    //
    // Размеры и области — в пикселях устройства: если они не совпадают, то
    // при приведении кадра к размеру раскладки области уезжают на пиксели, а
    // чтение цифр к этому очень чувствительно (число перестаёт узнаваться).
    //
    // Область числа энергии: цифры занимают x 329..377, y 876..900 (в
    // «Подземельях» число четырёхзначное и начинается левее — поэтому
    // область берём с запасом), число прижато к правому краю полоски, а
    // слева стоит фляконка — её в область не берём, иначе в разбор попадёт
    // лишний «глиф». Левый край области (316) отстоит от фляконки (её правый
    // край около 310) на 6 пикселей.
    return Layout{
        /*energy=*/cv::Rect(316, 874, 68, 30),
        /*energy_flask=*/cv::Rect(272, 872, 38, 40),
        // Шкала энергии в мобильном клиенте тёмная: заполнение по цвету
        // не читается, поэтому запасного источника значения здесь нет —
        // число читается только по цифрам.
        /*mana_bar=*/cv::Rect(),
        /*summon=*/cv::Rect(405, 845, 145, 72),
        // Кнопка умения героя: круглая, справа внизу над колодой.
        // Обод отката — жёлтое кольцо радиусом около 51 px, центр
        // (694, 965). Прямоугольник — сам обод (103x103).
        /*ability=*/cv::Rect(643, 914, 103, 103),
        /*card_row=*/cv::Rect(190, 915, 460, 100),
        /*card_count=*/5,
        /*canvas_size=*/cv::Size(941, 1030),
        /*digits_dir=*/"digits_emulator",
        /*close_x_min=*/0.60,
        /*scale=*/950.0 / kCanvasW,
        /*name=*/"мобильный клиент",
    };
}

cv::Size canonical_canvas_size(const Layout& layout) {
    // Размер холста, в котором настроены правила поиска кнопок, пороги и
    // шаблоны надписей: 492x804 у веб-клиента, 941x1030 у мобильного.
    //
    // Раскладку приводят к настоящему размеру кадра (Layout::scaled_to), и
    // после этого по ней не видно, какая это была раскладка: определяем по
    // масштабу — 1.0 у веб-клиента, 950/492 у мобильного (при приведении к
    // размеру кадра масштаб не меняется).
    if (layout.scale > 1.5) return cv::Size(941, 1030);
    return cv::Size(kCanvasW, kCanvasH);
}

const std::vector<ButtonRule>& button_rules() {
    // «Отмена» на экране подбора соперника — красно-оранжевая (H≈4-9),
    // крупная (117x48). Её не брал ни один прежний диапазон: чистый красный
    // ловил только мелкие значки, а оранжевый — кнопку PvP.
    static const std::vector<ButtonRule> rules = {
        // Крестик закрытия окна: красный круг с белым «X». Порог ширины
        // маленький: в мобильном клиенте кружок 32x36, а требовалось 39 —
        // и крестик не находился вовсе.
        {"close", {{0, 10}, {165, 180}}, 120, 255, 110, 255, 60, 14, 14, 48, 48},
        // Пороги заданы в пикселях веб-клиента и умножаются на масштаб, но
        // интерфейс мобильного клиента не в 1.93 раза крупнее: кнопка
        // «Отмена» там 147x50, а требовалось 116x58 — и она не находилась.
        {"cancel", {{0, 12}, {168, 180}}, 150, 255, 180, 255, 1200, 50, 20, 220, 90},
        // Синие кнопки: «Понятно», «Продолжить», «Забрать», стрелка «назад».
        // Порог площади маленький: стрелка «назад» в мобильном клиенте —
        // заметно меньше остальных кнопок, и при большом пороге она
        // отбрасывалась (а выйти из «Подземелья» больше нечем).
        {"continue", {{100, 132}}, 130, 255, 120, 255, 500, 30, 18, 400, 260},
        // Оранжевые кнопки: «PvP» в меню, «Заработать» на экране награды.
        // Кнопку «PvP» бот ищет по надписи — надёжнее цвета. Этот вид для
        // оранжевых кнопок вообще: иначе бот ждал матч там, где его нет.
        {"orange", {{12, 26}}, 140, 255, 140, 255, 1500, 40, 22, 300, 300, 0.55},
        {"fight", {{14, 34}}, 150, 255, 150, 255, 800, 40, 22, 300, 300, 0.55},
        {"watch", {{140, 168}}, 130, 255, 130, 255, 1200, 40, 22, 300, 300},
    };
    return rules;
}

