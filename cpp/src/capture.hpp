// Захват экрана и поиск холста игры.
#pragma once

#include <opencv2/core.hpp>

namespace rr {

// Снимок области экрана. На Wayland кадр берёт grim: mss через XWayland
// отдаёт чёрные кадры.
bool grab_screen(int x, int y, int w, int h, cv::Mat* out);

// Прямоугольник холста игры в снимке окна.
//
// У холста тёмно-синяя рамка (H≈106, S≈210) — по ней и находится область
// игры. Ищем по профилям строк и столбцов: у рамки есть горизонтальные
// полосы сверху и снизу и вертикальные слева и справа. Это устойчиво к
// затемнению экрана (на модальных окнах рамка почти чернеет, но оттенок
// и насыщенность сохраняются) и к тому, что окно разрывает кольцо рамки.
bool find_canvas_rect(const cv::Mat& frame, cv::Rect* out);

}  // namespace rr
