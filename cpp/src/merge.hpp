// Слияние пешек: поиск пары «одинаковых соседей» на своей половине поля.
//
// Отдельный модуль, потому что он не зависит от эталонов юнитов: пешки
// сравниваются друг с другом напрямую (у одинаковых юнитов почти совпадает
// круглый портрет, у разных — нет). Это работает на любых юнитах, даже
// которых нет в колоде, и не ломается, когда меняются наборы карт.
//
// Правила игры (HANDOFF, п. 17):
//   * слияние — перетаскивание одной пешки на такую же другую, на своей
//     половине поля;
//   * пешки стоят на сетке 3x5, сливать можно соседние клетки;
//   * сливать можно до 7 уровня: 1+1 → 2, 2+2 → 3, …, 6+6 → 7.
//     Разные ранги игра не принимает. Уже 7-й дальше не сливается.
#pragma once

#include <opencv2/core.hpp>

#include <vector>

#include "arena.hpp"

namespace rr {

// Пешка на поле.
struct Pawn {
    // Центр основания в координатах кадра (холста).
    cv::Point center;
    // Радиус основания: по нему приводится размер портрета, поэтому
    // сравнение не зависит от того, как близко стоит камера.
    int radius = 0;
    // Своя половина поля (нижняя) или чужая (верхняя).
    bool ours = false;
    // Круглое ли основание у пешки (диагностика, для выбора слияния не
    // используется: см. is_round_pedestal).
    //
    // ВНИМАНИЕ: форма основания кодирует ТИП карты, а не ранг юнита
    // (замеры в notes/ЗАДАЧА1_РАНГ.md). Ранга на поле в этой версии игры
    // не видно вовсе, поэтому по форме основания ранг определить нельзя.
    bool round_pedestal = true;
    // Заполненность основания (доля круга, занятого подставкой): круг ~0.9,
    // овал ~0.8, ромб ~0.65. По ней определяется тип карты (см.
    // pedestal_shape_class).
    double fill = 1.0;
};

// Форма основания — по ней определяется РАНГ юнита.
//
// ВНИМАНИЕ (24.10): прежнее мнение «форма кодирует ТИП карты» было
// неверным. Замер (notes/ЗАДАЧА1_РАНГ.md, исправление):
//
//   * в колоде у всех карт подставка круглая — это ранг 1;
//   * после слияния подставка на месте цели становится «каплей»:
//     заполненность падает с 0.94 до 0.76 (три опыта подряд);
//   * один и тот же юнит встречается на поле и с круглой подставкой, и с
//     «каплей» — значит, форма зависит от ранга, а не от карты;
//   * игра сливает только юнитов одного ранга: пара «ранг 1 + ранг 2»
//     отклоняется (живой опыт), «1 + 1» и «2 + 2» принимаются.
//
// | подставка | заполненность | ранг |
// |---|---|---|
// | круг      | >= 0.855       | 1    |
// | капля     | 0.72..0.855    | 2    |
// | щит       | < 0.72         | 3 и выше |
enum class PedestalShape {
    Rhombus,   // щит: ранг 3 и выше. Заполненность < 0.72.
    Oval,      // капля: ранг 2. Заполненность 0.72..0.855.
    Circle,    // круг: ранг 1. Заполненность >= 0.855.
};

// Форма основания по заполненности: ранг 1 / 2 / 3+.
PedestalShape pedestal_shape_class(double fill);

// То же, но строкой — для логов.
const char* pedestal_shape_name(PedestalShape shape);

// Ранг юнита по заполненности подставки.
//
// Ранг 1 — круглая подставка (>= 0.855), ранг 2 — «капля» (0.72..0.855),
// ранг 3 и выше — «щит» (< 0.72). Замер 24.10, см. PedestalShape.
inline const double kRank1Fill = 0.855;
inline const double kRank2Fill = 0.72;

// Ранг по номеру: 1, 2, 3.
inline int pedestal_rank(double fill) {
    if (fill >= kRank1Fill) return 1;
    if (fill >= kRank2Fill) return 2;
    return 3;
}

// Круглое ли основание у пешки.
//
// Это признак РАНГА: у юнита первого ранга подставка круглая, у слитого —
// «капля» или «щит». Ранг по ней определяется надёжно (см. PedestalShape).
bool is_round_pedestal(const cv::Mat& canvas, const Pawn& pawn);

// Заполненность основания: какая доля круга (того же радиуса, что и пятно
// основания) занята самим основанием. У круга ~0.9, у ромба ~0.65.
double pedestal_fill(const cv::Mat& canvas, const Pawn& pawn);

// Найти пешки на поле: круглые основания юнитов внутри половин арены.
//
// Основание — круг, на котором стоит юнит; он же и портрет (юнит нарисован
// круглым). Основания находятся надёжно, в отличие от совпадения с
// эталонами.
//
// `arena` — половины арены, найденные поиском арены (см. arena.hpp).
std::vector<Pawn> find_pawns(const cv::Mat& canvas, const ArenaFrame& arena);

// Пара пешек, которые можно слить.
struct MergePair {
    // Кого тянем (индекс в массиве пешек).
    int source = -1;
    // На кого тянем.
    int target = -1;
    // Насколько портреты похожи (1 — совпадают).
    double score = 0.0;
    // Расстояние между пешками в пикселях кадра.
    double distance = 0.0;
    // Стоят ли пешки на соседних клетках.
    bool adjacent = false;
    // Насколько пешки разного размера: |r1 - r2| / max(r1, r2).
    //
    // У юнита второго ранга подставка больше, и спрайт рисуется крупнее.
    // Замер по живых боях (tools/merge_failure_analysis.py): у неудачных пар
    // размеры расходятся чаще, чем у удачных.
    double size_diff = 0.0;
    // Ранг обеих пешек — по форме подставки (см. PedestalShape).
    //
    // Игра сливает только юнитов одного ранга: «ранг 1 + ранг 2» отклоняет
    // (живой опыт 24.10), «1 + 1» и «2 + 2» принимает.
    int rank_source = 1;
    int rank_target = 1;
    // Одинаковый ли ранг. Если ранги разные — пара почти бесполезна.
    bool same_rank = true;
};

// Порог похожести портретов: выше — сливаются только совпадающие юниты.
inline const double kMergeMatchMin = 0.65;
// Порог похожести для попытки слияния: пара, чьи портреты похожи слабее,
// боту сливать не стоит.
//
// Замер 25.10 (46 попыток, PvP): пары с похожестью >= 0.85 сливаются в
// 100 % случаев (34 из 34), 0.75..0.85 — в 58 %, ниже 0.75 — в 12 %.
// Живой бой 26.10 после соседства по сетке: >= 0.80 — 14/14, 0.75..0.80 —
// 0/2 (оба промаха). Порог 0.78 оставлял ложные портреты.
inline const double kMergeTryMin = 0.82;
// Порог «хорошей» пары: такие сливаются почти всегда.
//
// (замер 25.10: 0.85..0.95 — 7 из 7 успехов)
inline const double kMergeTryGood = 0.85;
// Порог «очень похожей» пары: такие сливаются почти всегда.
//
// (замер: пары одного типа с похожестью >= 0.90 сливаются в 96 % случаев)
inline const double kMergeTryStrict = 0.90;
// Порог, ниже которого пара не сливается никогда (иначе бот встанет, если
// на доске нет одинаковых юнитов).
inline const double kMergeTryFloor = 0.65;
// Насколько пешки могут отличаться размером при попытке слияния: больше —
// это юниты разного ранга, и игра такую пару не принимает.
inline const double kMergeSizeMax = 0.12;
// Разница размеров, за которой слияние заметно хуже.
//
// Замер 25.10 (77 попыток, PvP): разница размеров до 8 % — успех в 95 %
// случаев, 8..12 % — в 66 %, больше — в 50 %. Разница размеров — верный
// признак юнита второго ранга: он нарисован крупнее.
inline const double kMergeSizeGood = 0.08;
// Запасной порог размера: если строгий не проходит, но доска забита,
// пробуем пешки чуть разного размера. Выше ~16 % в живых боях 26.10
// успех падал до трети попыток (это уже другой ранг).
inline const double kMergeSizeRelaxed = 0.16;
// Максимальный ранг юнита: 7-й дальше не сливается (6+6 → 7).
inline const int kMergeRankMax = 7;

// Найти пары для слияния.
//
// Условия: обе пешки свои, стоят на соседних клетках (в том числе по
// диагонали) и одного размера. Оценка похожести портретов — в поле score:
// слиять нужно пары с score не меньше kMergeMatchMin (сравнение делает
// вызывающий, чтобы можно было подобрать порог замером).
//
// Если пар несколько, в начале списка — самая похожая; при равенстве — самая
// близкая (её видно лучше всего).
std::vector<MergePair> find_merge_pairs(const cv::Mat& canvas, const std::vector<Pawn>& pawns);

// Оценка вероятности успеха слияния для пары.
//
// Таблица собрана по замерам живых боёв (tools/merge_pairs_stats.py,
// tools/merge_policy_eval.py; 46 попыток 25.10 в PvP):
//
//   пары одного ранга:  похожесть >= 0.90 — 96 % успеха,
//                       0.85..0.90 — 92 %, 0.78..0.85 — 58 %, ниже — 12 %;
//   пары разных рангов: игра их не принимает (живой опыт 24.10:
//                       «ранг 1 + ранг 2» — отказ), шанс близок к нулю.
//
// Главный признак — похожесть портретов (палитра, это же и признак типа
// карты). Ранг — жёсткое условие: разные ранги сливать бессмысленно.
double merge_success_estimate(const MergePair& pair);

// Сколько своих пешек похожи на указанную.
//
// Это проверка результата слияния: после слияния два юнита превращаются в
// одного, и портрет у него уже другой (появляется цифра ранга) — значит,
// похожих пешек становится на одну меньше.
int count_same_pawns(const cv::Mat& canvas, const std::vector<Pawn>& pawns, const Pawn& reference);

// Похожесть двух пешек по палитре основания (1 — совпадают).
//
// Сравниваются не пиксели (у юнитов анимация), а палитра круга основания.
double pawn_similarity(const cv::Mat& canvas, const Pawn& a, const Pawn& b);

// Сдвиг поля между двумя кадрами: медиана перемещений совпавших пешек.
//
// Камера в бою едет (за кадр — до 70 px), и без сдвига координаты пешек
// устаревают: слияние попадает мимо цели. По положению арены сдвиг
// определить нельзя — детектор арены гуляет на десятки пикселей, а пешки
// стоят на сетке и сдвигаются одинаково.
//
// Пешки сопоставляются по ближайшему соседу (в пределах max_shift), сдвиг
// берётся медианой, чтобы единичная ошибка детектора не портила результат.
cv::Point estimate_pawn_shift(const std::vector<Pawn>& before, const std::vector<Pawn>& after,
                               int max_shift = 60);

// Пешка рядом с предсказанной позицией.
//
// Ищет среди пешек ту, что стоит ближе всего к предсказанной точке и
// похожа на опорную (по палитре). Возвращает индекс в pawns или -1.
int find_pawn_near(const cv::Mat& canvas, const std::vector<Pawn>& pawns,
                   const Pawn& reference, cv::Point predicted, int radius,
                   double min_similarity = 0.6);

}  // namespace rr
